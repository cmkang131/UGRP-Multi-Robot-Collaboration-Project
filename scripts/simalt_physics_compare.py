"""Linux-only, default-off simalt2 rigid robot/box command-tape diagnostic.

No policy, training, physics overrides or live truth feedback. The tape is
generated by the frozen issued-command decoder without advancing physics.
State/contact arrays are evaluator outputs only. Tick/SIM limits determine
work; an external wall timeout may enforce the user's resource cap.
"""
import argparse
from collections import deque
from contextlib import contextmanager
import hashlib
import inspect
import json
import math
from pathlib import Path
import platform
import socket
import subprocess
import sys
import time
import traceback
import warnings


def write(p, x):
    Path(p).write_text(json.dumps(x, indent=2, allow_nan=False) + '\n')


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def prepare(a):
    import xml.etree.ElementTree as ET
    import numpy as np
    import mujoco
    from simalt_pilot import world_for, trace_rows
    from sim.grasp_act_port import DutyActPort
    from scripts.run_grasp_act_teacher import apply
    plan = json.loads(a.plan.read_text())
    world, scene = world_for(plan, False)
    try:
        root = ET.fromstring(world.scene_xml)
        removed = set()
        wb = root.find('worldbody')
        for body in list(wb):
            if body.tag == 'body' and body.get('name') not in ('r1__robot', 'cargo_cyan_2'):
                removed.update(e.get('name') for e in body.iter() if e.get('name'))
                wb.remove(body)
        for section in ('equality','actuator','sensor','contact','tendon'):
            parent = root.find(section)
            if parent is None:
                continue
            for e in list(parent):
                if any(v in removed or v.startswith(('r2__','r3__')) for v in e.attrib.values()):
                    parent.remove(e)
        xml = ET.tostring(root, encoding='unicode')
        (a.out/'scene.xml').write_text(xml)
        m = mujoco.MjModel.from_xml_string(xml)
        d = mujoco.MjData(m)
        for j in range(m.njnt):
            full = world.model.joint(m.joint(j).name).id
            nq = (m.jnt_qposadr[j+1] if j+1<m.njnt else m.nq)-m.jnt_qposadr[j]
            nv = (m.jnt_dofadr[j+1] if j+1<m.njnt else m.nv)-m.jnt_dofadr[j]
            d.qpos[m.jnt_qposadr[j]:m.jnt_qposadr[j]+nq] = world.data.qpos[world.model.jnt_qposadr[full]:world.model.jnt_qposadr[full]+nq]
            d.qvel[m.jnt_dofadr[j]:m.jnt_dofadr[j]+nv] = world.data.qvel[world.model.jnt_dofadr[full]:world.model.jnt_dofadr[full]+nv]
        initial_qpos, initial_qvel = d.qpos.copy(), d.qvel.copy()
        indices = [world.model.actuator(m.actuator(i).name).id for i in range(m.nu)]
        origin = float(world.data.time)
        robot = world.robot('r1')
        base_port = DutyActPort(world, 'r1', allow_reverse=True, allow_mecanum=True)
        initial_pwm = {str(k):int(v) for k,v in base_port._servo_pulses.items()}
        stop = {'t':0.,'wheels':[0.]*4,'duration_s':[0.]*4,'pwm':initial_pwm}
        cases = []
        # 35% wheel pulse comes from frozen duty_wheels' real dead-zone contract.
        # 1s motion then 3s stop is a diagnostic stimulus, not an acceptance gate.
        for name, pattern in [('forward',[1,1,1,1]),('side',[-1,1,1,-1]),('turn',[-1,1,-1,1])]:
            rows = [{'t':i*.1,'phase':name if i<10 else 'stop', 'command':
                     {**stop,'wheels':[.35*x for x in pattern] if i<10 else [0.]*4,
                      'duration_s':[.1]*4 if i<10 else [0.]*4}} for i in range(40)]
            cases.append((name,rows))
        cases.append(('grip',trace_rows(a.trace)))  # original close/3s hold/release trace
        tapes = {}
        manifest = []
        initial_ctrl = world.data.ctrl.copy()
        for name, rows in cases:
            world.data.ctrl[:] = initial_ctrl
            robot.set_servo_pulses({int(k):v for k,v in initial_pwm.items()})
            robot.set_motor_commands([0.]*4)
            world.data.time = origin
            port = DutyActPort(world, 'r1', allow_reverse=True, allow_mecanum=True)
            previous = {'pwm':initial_pwm}
            previous_drive = np.zeros(4,dtype=int)
            tape = []
            dt = float(m.opt.timestep)
            substeps = round(.1/dt)
            for i,row in enumerate(rows):
                now = origin+(i*substeps)*dt
                apply(port,{**row['command'],'t':now},now,previous)
                previous = row['command']
                for k in range(substeps):
                    now = origin+(i*substeps+k)*dt
                    world.data.time = now
                    port.tick(now)
                    effective, previous_drive = world.drive_parameters.command_step(robot.motor_command, previous_drive)
                    world.data.ctrl[robot.wheel_act] = world.drive_parameters.torque_cap_nm*effective
                    tape.append(world.data.ctrl[indices].copy())
            tapes[name] = np.asarray(tape)
            manifest.append({'name':name,'steps':len(tape),'sim_s':len(tape)*dt,'phases':[r['phase'] for r in rows]})
        np.savez_compressed(a.out/'fixture.npz', qpos=initial_qpos, qvel=initial_qvel, **tapes)
        write(a.out/'fixture.json',{'sha':a.sha,'teacher_sha':'6f057f7e97c1a3aec9e8c398b8d9068e27b25df8',
            'source_plan_sha256':sha(a.plan),'source_trace_sha256':sha(a.trace),
            'xml_sha256':sha(a.out/'scene.xml'),'tape_sha256':sha(a.out/'fixture.npz'),
            'model_counts':{k:int(getattr(m,k)) for k in ('nq','nv','nu','nbody','ngeom','neq')},
            'cases':manifest,'removed_bodies_and_names':sorted(removed),
            'physics_overrides':{},'control_generation_physics_steps':0,
            'note':'Full scene reset is canonical; only tape generation advances the issued-command clock without stepping physics.'})
    finally:
        world.close()


@contextmanager
def unused_efm(m,d):
    from mujoco_warp._src import io
    from simalt_numeric_audit import inactive_efm_field
    original = io._create_array
    def allocate(data,spec,sizes,batch_size=1):
        frame = inspect.currentframe().f_back
        f = frame.f_locals.get('f')
        if frame.f_code.co_name=='put_data' and inactive_efm_field(getattr(f,'name',None),int(m.opt.integrator),
                int(d.efm_active),int(m.nflex),int(d.nefmK),int(d.nefmT),int(d.nefmA)):
            return original(None,spec,sizes,batch_size)
        return original(data,spec,sizes,batch_size)
    io._create_array=allocate
    try:
        yield
    finally:
        io._create_array=original


def run(a):
    import numpy as np
    import mujoco
    m = mujoco.MjModel.from_xml_path(str(a.fixture/'scene.xml'))
    fixture = np.load(a.fixture/'fixture.npz')
    meta = json.loads((a.fixture/'fixture.json').read_text())
    report = {'sha':a.sha,'engine':a.engine,'mujoco_version':mujoco.__version__,'nworld':a.nworld,
              'script_sha256':sha(__file__),
              'fixture_sha256':sha(a.fixture/'fixture.npz'),'xml_sha256':sha(a.fixture/'scene.xml'),
              'training':False,'renderer':'none; physics-only; state ring buffer for offline rendering',
              'status':'running','attempted':0,'completed':0,'failure':0,'HOST_ERROR':0,'cap_end':False,
              'steps_accepted':0,'cases':[],'physics_overrides':{},'rejection_table':str(a.out/'rejection_table.json')}
    if a.gcp2_v1:
        from simalt_host import gcp2_identity
        report['execution_host']=gcp2_identity()
        report['unused_efm_v1']=a.unused_efm_v1
    write(a.out/'result.json',report)
    states={}; recent=deque(maxlen=100)  # 10s x 10Hz evaluator recording, independent of training/control
    start=time.perf_counter()
    if m.opt.noslip_iterations != 10 or np.any(m.eq_active0):
        raise RuntimeError('noslip=10 and weld OFF required')
    report['options']={k:float(getattr(m.opt,k)) for k in ('timestep','iterations','ls_iterations','noslip_iterations','noslip_tolerance','tolerance','integrator','cone','solver')}
    report['physics_hashes']={k:hashlib.sha256(getattr(m,k).tobytes()).hexdigest() for k in ('geom_friction','pair_friction','body_mass','body_inertia','geom_solref','geom_solimp')}
    rgb_recent=deque(maxlen=100)
    if a.batch_render_v1:
        if not a.gcp2_v1 or a.engine!='warp':
            raise RuntimeError('batch render is explicit gcp2 Warp diagnostic only')
        from sim import masterpi_camera_review_v3 as camera
        from sim.masterpi_camera_profile import raw_fisheye_remap
        import cv2
        cid=m.camera('r1__robot_cam').id
        m.cam_pos[cid]=camera.POSITION_M;m.cam_quat[cid]=camera.QUAT_WXYZ
        for name in ('camera_bracket','camera_body','camera_lens_visual'):
            gid=mujoco.mj_name2id(m,mujoco.mjtObj.mjOBJ_GEOM,'r1__'+name)
            if gid>=0:m.geom_group[gid]=5
        mx,my=raw_fisheye_remap(640,480)
        report['renderer']='MJWarp batch RGB640x480 at10Hz, readback+OpenCV fisheye; no policy/training/JPEG time'
    if a.engine=='warp':
        import warp as wp
        import mujoco_warp as mjw
        wp.init()
        wm=mjw.put_model(m)
        report['warp_version']=wp.__version__
        report['backend_solver_tolerance']=float(wm.opt.tolerance.numpy().item())
        if a.gcp2_v1:
            # io.py:433-436 at pinned 57b4692 clamps to 1e-6 for float32.
            # Preserve the source scene's 1e-8, rather than silently relaxing it.
            wm.opt.tolerance.fill_(float(m.opt.tolerance))
            report['backend_solver_tolerance_before_preservation']=report['backend_solver_tolerance']
            report['backend_solver_tolerance']=float(wm.opt.tolerance.numpy().item())
        if wm.opt.noslip_iterations != 10:
            raise RuntimeError('noslip ignored')
        if a.batch_render_v1:
            rc=mjw.create_render_context(m,nworld=a.nworld,cam_res=(640,480),
                render_rgb=True,render_depth=False,render_seg=False,
                use_textures=True,use_shadows=True,enabled_geom_groups=[0,1,2,3],
                cam_active=['r1__robot_cam'])
            rgb=wp.zeros((a.nworld,480,640),dtype=wp.vec3)
        # Canonical reference maxima size buffers; round to a power of 2 for
        # allocation only. This is not an accepted-contact or physics threshold.
        ref=json.loads(a.reference.read_text())
        ncon=2**math.ceil(math.log2(max(1,max(c['max_ncon'] for c in ref['cases']))))
        nefc=2**math.ceil(math.log2(max(1,max(c['max_nefc'] for c in ref['cases']))))
        report['capacities']={'nconmax':ncon,'njmax':nefc,'basis':'next power of 2 of observed C reference maxima'}
        @wp.kernel
        def controls(tape:wp.array2d[wp.float32],tick:wp.array[wp.int32],ctrl:wp.array2d[wp.float32]):
            w=wp.tid()
            for j in range(ctrl.shape[1]):
                ctrl[w,j]=tape[tick[0],j]
        @wp.kernel
        def advance(tick:wp.array[wp.int32]):
            tick[0]=tick[0]+1
        def check(wd):
            overflow=wd.overflow.numpy()
            if np.any(overflow):
                raise RuntimeError('MJWarp capacity overflow '+str(overflow.tolist()))
            if not np.isfinite(wd.qpos.numpy()).all() or not np.isfinite(wd.qvel.numpy()).all():
                raise RuntimeError('MJWarp nonfinite state')
    try:
        for case in meta['cases']:
            if a.only and case['name'] != a.only:
                continue
            report['attempted']+=1
            name=case['name'];tape=fixture[name];dt=float(m.opt.timestep)
            d=mujoco.MjData(m);d.qpos[:]=fixture['qpos'];d.qvel[:]=fixture['qvel'];d.ctrl[:]=tape[0]
            mujoco.mj_forward(m,d)
            if a.engine=='warp':
                # MuJoCo 3.16's reset contact set can exceed 3.12's sampled
                # maximum. Include the actual import counts, as put_data
                # requires. This is workspace allocation, not contact removal.
                ncon=max(ncon,2**math.ceil(math.log2(max(1,int(d.ncon)))))
                nefc=max(nefc,2**math.ceil(math.log2(max(1,int(d.nefc)))))
                report['capacities'].update(nconmax=ncon,njmax=nefc,
                    basis='next power of 2 of observed C3.12 trace maxima and actual C3.16 import counts')
                if a.gcp2_v1 and not a.unused_efm_v1:
                    raise RuntimeError('simalt3 explicitly requires --unused-efm-v1')
                with unused_efm(m,d): wd=mjw.put_data(m,d,nworld=a.nworld,nconmax=ncon,njmax=nefc)
                report.update(status='compiling_first_step',put_data_passed=True)
                write(a.out/'result.json',report)
                mjw.step(wm,wd);wp.synchronize();check(wd)
                if a.batch_render_v1:
                    # Match the C owner's _sync_real_camera_mount/mj_forward:
                    # expose post-integration body/camera transforms to rendering.
                    mjw.kinematics(wm,wd);mjw.camlight(wm,wd)
                    mjw.refit_bvh(wm,wd,rc);mjw.render(wm,wd,rc);mjw.get_rgb(rc,0,rgb);wp.synchronize()
                report.update(status='first_step_pass_only',first_step_passed=True)
                write(a.out/'result.json',report)
                # Warm-up is recorded separately, and discarded before the trace.
                with unused_efm(m,d): wd=mjw.put_data(m,d,nworld=a.nworld,nconmax=ncon,njmax=nefc)
                wt=wp.array(tape.astype(np.float32),dtype=wp.float32)
                tick=wp.zeros(1,dtype=wp.int32)
                # 16 divides the contractual 400 physics ticks per control tick.
                # It batches launch overhead, without altering dt or commands.
                with wp.ScopedCapture() as capture:
                    for k in range(16):
                        wp.launch(controls,dim=a.nworld,inputs=[wt,tick,wd.ctrl])
                        mjw.step(wm,wd)
                        wp.launch(advance,dim=1,inputs=[tick])
                graph=capture.graph
            cr={'name':name,'status':'running','max_ncon':int(d.ncon),'max_nefc':int(d.nefc),
                'physics_wall_s':0.,'evaluator_wall_s':0.,
                'batch_render_wall_s':0.,'readback_fisheye_wall_s':0.,'RGB_frames':0,
                'sim_s':0.,'wall_s':0.,'sample_count':0}
            report['cases'].append(cr)
            values=[];contacts=[];forces=[]
            states[name]=values  # preserve partial failure timeline, not only completed cases
            cs=time.perf_counter()
            for begin in range(0,len(tape),400):
                ps=time.perf_counter()
                if a.engine=='cpu':
                    for j in range(begin,begin+400):
                        d.ctrl[:]=tape[j];mujoco.mj_step(m,d)
                else:
                    for j in range(25):wp.capture_launch(graph)
                    wp.synchronize()
                cr['physics_wall_s']+=time.perf_counter()-ps
                if a.batch_render_v1:
                    rs=time.perf_counter()
                    mjw.kinematics(wm,wd);mjw.camlight(wm,wd)
                    mjw.refit_bvh(wm,wd,rc);mjw.render(wm,wd,rc);mjw.get_rgb(rc,0,rgb);wp.synchronize()
                    cr['batch_render_wall_s']+=time.perf_counter()-rs
                    rs=time.perf_counter()
                    raw=np.clip(rgb.numpy()*255,0,255).astype(np.uint8)
                    for w in range(a.nworld):
                        frame=cv2.remap(raw[w],mx,my,cv2.INTER_LINEAR,borderMode=cv2.BORDER_CONSTANT)
                        if w==0:rgb_recent.append(((begin+400)*dt,frame.copy()))
                    cr['readback_fisheye_wall_s']+=time.perf_counter()-rs
                    cr['RGB_frames']+=a.nworld
                es=time.perf_counter()
                if a.engine=='warp':
                    check(wd)
                    mjw.get_data_into(d,m,wd,world_id=0)
                    mujoco.mj_kinematics(m,d)  # evaluator body poses only; no forward/contact recomputation
                if not np.isfinite(d.qpos).all() or not np.isfinite(d.qvel).all():
                    raise RuntimeError('nonfinite state')
                report['steps_accepted']+=400*a.nworld
                values.append(np.r_[d.qpos,d.qvel].copy())
                recent.append({'case':name,'t':float(d.time),'qpos':d.qpos.tolist()})
                cr['max_ncon']=max(cr['max_ncon'],int(d.ncon));cr['max_nefc']=max(cr['max_nefc'],int(d.nefc))
                contacts.append({'t':float(d.time),'pairs':sorted([sorted([m.geom(int(c.geom[0])).name,m.geom(int(c.geom[1])).name]) for c in d.contact]),
                                 'minimum_dist_m':float(min(d.contact.dist)) if d.ncon else None})
                finger=[0.,0.]
                for j,c in enumerate(d.contact):
                    f=np.zeros(6);mujoco.mj_contactForce(m,d,j,f)
                    for k,side in enumerate(('left','right')):
                        if m.geom('r1__'+side+'_finger').id in c.geom:
                            finger[k]+=float(np.linalg.norm(f[:3]))
                forces.append(finger)
                cr['evaluator_wall_s']+=time.perf_counter()-es
                cr.update(sim_s=(begin+400)*dt,wall_s=time.perf_counter()-cs,sample_count=len(values))
                if (begin//400)%10==0:write(a.out/'result.json',report)
            cr.update(status='complete',wall_s=time.perf_counter()-cs,
                      physics_only_SIM_s_per_wall_s=len(tape)*dt*a.nworld/cr['physics_wall_s'],
                      physics_plus_RGB_SIM_s_per_wall_s=(len(tape)*dt*a.nworld/(cr['physics_wall_s']+cr['batch_render_wall_s']+cr['readback_fisheye_wall_s'])) if a.batch_render_v1 else None,
                      total_sim_seconds_per_wall_second=len(tape)*dt*a.nworld/(time.perf_counter()-cs),
                      per_world_sim_seconds_per_wall_second=len(tape)*dt/(time.perf_counter()-cs))
            states[name]=np.asarray(values)
            write(a.out/(name+'-contacts.json'),contacts)
            write(a.out/(name+'-finger-forces.json'),forces)
            report['completed']+=1
            write(a.out/'result.json',report)
        report['status']='complete'
    except KeyboardInterrupt:
        report.update(status='cap_end',cap_end=True,error='supervised resource/time cap or interrupt')
    except Exception as e:
        report.update(status='rejected',failure=1,error_type=type(e).__name__,error=str(e),traceback=traceback.format_exc())
    finally:
        np.savez_compressed(a.out/'states.npz',**states)
        if rgb_recent:
            # Recording-only ring: world0 final10 SIM seconds, independent of control/training.
            folder=a.out/'own-RGB-ring';folder.mkdir(exist_ok=True)
            for i,(t,frame) in enumerate(rgb_recent):
                cv2.imwrite(str(folder/f'{i:03d}-{t:.1f}.jpg'),cv2.cvtColor(frame,cv2.COLOR_RGB2BGR))
            report['RGB_ring']={'path':str(folder),'hz':10,'max_frames':100,'saved_frames':len(rgb_recent),
                'world':0,'bytes':sum(p.stat().st_size for p in folder.iterdir()),'recording_only':True}
        if a.engine=='warp':
            try:
                report['gpu_memory_end']=subprocess.check_output(['nvidia-smi','--query-gpu=memory.used,memory.total,utilization.gpu','--format=csv,noheader,nounits'],text=True).strip()
            except Exception as e:report['gpu_memory_query_error']=str(e)
        write(a.out/'state-ring-buffer.json',{'hz':10,'max_frames':100,'frames':list(recent),
              'note':'No online renderer. Evaluator poses permit later rendering; not a saved RGB buffer.'})
        report['wall_s']=time.perf_counter()-start
        report['rejections']=[] if not report['failure'] else [{'category':'numeric_or_engine_compatibility',
            'reason':report['error'],'blocking_object':report.get('error_type','engine'),
            'minimum_gap_m':None,'minimum_gap_status':'not_geometric'}]
        write(a.out/'rejection_table.json',{'funnel':[{'gate':'command cases','entered':report['attempted'],'passed':report['completed'],'rejected':report['failure']}],
              'rejections':report['rejections'],'raw_path':str(a.out),'reproduction':sys.argv})
        write(a.out/'result.json',report)
    print(json.dumps(report,indent=2))


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('action',choices=['prepare','run'])
    p.add_argument('--source',type=Path,required=True)
    p.add_argument('--plan',type=Path)
    p.add_argument('--trace',type=Path)
    p.add_argument('--fixture',type=Path)
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--sha',required=True)
    p.add_argument('--engine',choices=['cpu','warp'],default='cpu')
    p.add_argument('--reference',type=Path)
    p.add_argument('--nworld',type=int,default=1)
    p.add_argument('--only')
    p.add_argument('--enabled',action='store_true')
    p.add_argument('--gcp2-v1',action='store_true')
    p.add_argument('--unused-efm-v1',action='store_true',help='explicit inactive-workspace adapter opt-in for simalt3')
    p.add_argument('--batch-render-v1',action='store_true',help='default OFF: batched own RGB diagnostic including readback/fisheye')
    a=p.parse_args()
    if a.gcp2_v1:
        from simalt_host import gcp2_identity
        host=gcp2_identity()
        if a.engine=='warp' and host['instance']!='ugrp-act-l4-gcp2':
            p.error('MJWarp requires the admitted L4')
    if not a.enabled or platform.system()!='Linux' or (not a.gcp2_v1 and socket.gethostname().split('.')[0]!='ugrp-act-l4-pilot1'):
        p.error('explicit Linux L4-only opt-in required')
    sys.path.insert(0,str(a.source))
    warnings.filterwarnings('error',message='.*overflow.*',category=RuntimeWarning)
    a.out.mkdir(parents=True,exist_ok=False)
    (prepare if a.action=='prepare' else run)(a)


if __name__=='__main__':main()
